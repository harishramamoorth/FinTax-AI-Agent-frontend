function storedLanguage(): PortalLanguage {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'de' || saved === 'ar') return saved;
  } catch {
    // Language selection remains available for this session if storage is blocked.
  }
  return 'en';
}

interface PortalLanguageState {
  language: PortalLanguage;
  setLanguage(language: PortalLanguage): void;
}

export const usePortalLanguage = create<PortalLanguageState>((set) => ({
  language: storedLanguage(),
  setLanguage: (language) => {
    try {
      localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Keep the selected language in memory when storage is blocked.
    }
    set({ language });
  },
}));

export function portalText(language: PortalLanguage, key: MessageKey): string {
  return translations[language][key];
}

export function portalExtractionNote(language: PortalLanguage, note: string): string {
  const t = (key: MessageKey) => portalText(language, key);
  if (note.startsWith('No readable text or cell values')) return t('noReadableValuesNote');
  if (note.startsWith('No readable text was found')) return t('noReadablePdfNote');
  if (note.startsWith('Text was extracted locally')) return t('extractedTextNote');
  if (note.startsWith('Cell values extracted from this legacy Excel')) return t('legacyExcelNote');
  if (note.startsWith('Text was read locally with')) {
    const translated = note.includes('Tesseract OCR') ? t('pdfOcrNote') : t('pdfTextLayerNote');
    const details = [
      note.includes('OCR is capped at') ? t('ocrPageLimitNote') : '',
      note.includes('Arabic OCR language data was requested') ? t('arabicOcrCaution') : '',
    ].filter(Boolean);
    return [translated, ...details].join(' ');
  }
  return note;
}

export function portalCategory(language: PortalLanguage, category: string): string {
  return categoryLabels[language][category] ?? category.replace(/_/g, ' ');
}
